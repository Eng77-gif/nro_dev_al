DROP TABLE IF EXISTS `season_event`, `season_event_drop`, `season_event_exchange`, `season_event_top`, `season_event_top_reward`;
CREATE TABLE `season_event` (
  `id` int(11) NOT NULL,
  `name` varchar(64) NOT NULL,
  `lunar` tinyint(1) NOT NULL DEFAULT 0 COMMENT '1 = ngày âm lịch',
  `month` int(11) NOT NULL,
  `day` int(11) NOT NULL,
  `days_before` int(11) NOT NULL DEFAULT 0 COMMENT 'bắt đầu trước ngày chính',
  `days_after` int(11) NOT NULL DEFAULT 0 COMMENT 'kết thúc sau ngày chính',
  `enabled` tinyint(1) NOT NULL DEFAULT 1,
  `bosses` varchar(255) NOT NULL DEFAULT '' COMMENT 'bossId:số lượng,...',
  `description` varchar(1500) NOT NULL DEFAULT '',
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
CREATE TABLE `season_event_drop` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `event_id` int(11) NOT NULL,
  `item_id` int(11) NOT NULL,
  `rate` int(11) NOT NULL COMMENT 'tỉ lệ /10000 mỗi lần hạ quái hoặc boss',
  `qty_min` int(11) NOT NULL DEFAULT 1,
  `qty_max` int(11) NOT NULL DEFAULT 1,
  `source` varchar(8) NOT NULL DEFAULT 'mob' COMMENT 'mob hoặc boss',
  `daily_max` int(11) NOT NULL DEFAULT 0 COMMENT 'tối đa mỗi ngày, 0 = không giới hạn',
  `mobs` varchar(255) NOT NULL DEFAULT '' COMMENT 'id mẫu quái (hoặc id boss) được rơi, rỗng = tất cả',
  `maps` varchar(255) NOT NULL DEFAULT '' COMMENT 'id bản đồ được rơi, rỗng = tất cả',
  PRIMARY KEY (`id`),
  KEY `event_id` (`event_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
CREATE TABLE `season_event_exchange` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `event_id` int(11) NOT NULL,
  `grp` varchar(32) NOT NULL DEFAULT 'Đổi\nquà' COMMENT 'nhóm nút trong menu',
  `name` varchar(64) NOT NULL,
  `need` varchar(255) NOT NULL DEFAULT '' COMMENT 'itemId:số lượng,...',
  `gold` bigint(20) NOT NULL DEFAULT 0,
  `gem` int(11) NOT NULL DEFAULT 0,
  `ruby` int(11) NOT NULL DEFAULT 0,
  `cost_point` int(11) NOT NULL DEFAULT 0 COMMENT 'điểm sự kiện phải trả',
  `reward_item` int(11) NOT NULL COMMENT 'vật phẩm nhận, hoặc box_id của item_box_reward khi open_now = 1',
  `reward_qty` int(11) NOT NULL DEFAULT 1,
  `reward_qty_max` int(11) NOT NULL DEFAULT 0,
  `reward_days` varchar(64) NOT NULL DEFAULT '' COMMENT 'các mức HSD (ngày), rỗng = vĩnh viễn',
  `perm_rate` int(11) NOT NULL DEFAULT 0 COMMENT '% ra vĩnh viễn khi có HSD',
  `bonus_item` int(11) NOT NULL DEFAULT 0,
  `bonus_rate` int(11) NOT NULL DEFAULT 0 COMMENT '% nhận thêm bonus_item',
  `open_now` tinyint(1) NOT NULL DEFAULT 0 COMMENT '1 = mở ngay 1 phần quà ngẫu nhiên (tặng quà NPC)',
  `event_point` int(11) NOT NULL DEFAULT 0 COMMENT 'điểm sự kiện được cộng',
  `top_id` int(11) NOT NULL DEFAULT 0,
  `top_point` int(11) NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  KEY `event_id` (`event_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
CREATE TABLE `season_event_top` (
  `id` int(11) NOT NULL,
  `event_id` int(11) NOT NULL,
  `name` varchar(64) NOT NULL,
  PRIMARY KEY (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
CREATE TABLE `season_event_top_reward` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `top_id` int(11) NOT NULL,
  `rank_from` int(11) NOT NULL,
  `rank_to` int(11) NOT NULL,
  `item_id` int(11) NOT NULL COMMENT '-1 vàng, -2 ngọc xanh, -3 hồng ngọc',
  `qty` int(11) NOT NULL DEFAULT 1,
  `hsd_days` varchar(16) NOT NULL DEFAULT '' COMMENT 'rỗng = vĩnh viễn',
  PRIMARY KEY (`id`),
  KEY `top_id` (`top_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
CREATE TABLE IF NOT EXISTS `season_event_point` (
  `top_id` int(11) NOT NULL,
  `player_id` bigint(20) NOT NULL,
  `name` varchar(64) NOT NULL DEFAULT '',
  `points` int(11) NOT NULL DEFAULT 0,
  PRIMARY KEY (`top_id`,`player_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
CREATE TABLE IF NOT EXISTS `season_event_reward_pending` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `player_id` bigint(20) NOT NULL,
  `top_id` int(11) NOT NULL,
  `rank_no` int(11) NOT NULL,
  PRIMARY KEY (`id`),
  KEY `player_id` (`player_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
